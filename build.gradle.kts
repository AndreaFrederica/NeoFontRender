// A named task class instead of a doLast lambda: script lambdas capture the build
// script instance, which the configuration cache cannot serialize.
abstract class GenerateBuildFeaturesTask : DefaultTask() {
    @get:Input
    abstract val renderStatsEnabled: Property<Boolean>

    @get:OutputFile
    abstract val outputFile: RegularFileProperty

    @TaskAction
    fun generate() {
        val target = outputFile.get().asFile
        target.parentFile.mkdirs()
        target.writeText(
            """package neofontrender.build;

/** Build-time feature switches. Generated by Gradle; do not edit. */
public final class BuildFeatures {
    public static final boolean RENDER_STATS = ${renderStatsEnabled.get()};

    private BuildFeatures() {}
}
""",
            Charsets.UTF_8,
        )
    }
}

val renderStatsEnabledValue = providers.gradleProperty("enable_render_stats")
    .map(String::toBoolean)
    .getOrElse(false)
val generatedBuildFeaturesDir = layout.buildDirectory.dir("generated/sources/buildFeatures/java/main")

val generateBuildFeatures = tasks.register<GenerateBuildFeaturesTask>("generateBuildFeatures") {
    renderStatsEnabled.set(renderStatsEnabledValue)
    outputFile.set(generatedBuildFeaturesDir.map {
        it.file("neofontrender/build/BuildFeatures.java")
    })
}

plugins.withId("java") {
    extensions.configure<SourceSetContainer>("sourceSets") {
        named("main") {
            java.srcDir(generatedBuildFeaturesDir)
            // engine:text-core is pure Java without MC deps; on main it ships as a
            // contained subproject, here its sources compile into the root jar.
            java.srcDir("engine/text-core/src/main/java")
        }
    }
    tasks.named("compileJava") {
        dependsOn(generateBuildFeatures)
    }
    tasks.matching { it.name == "sourcesJar" }.configureEach {
        dependsOn(generateBuildFeatures)
    }
}
